def write(name, feats):
    out = ROOT / "data" / "points" / name
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps({"type": "FeatureCollection", "features": feats}, ensure_ascii=False, indent=2) + "\n")
    return out


